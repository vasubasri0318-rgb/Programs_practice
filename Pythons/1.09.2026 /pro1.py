a = int(input("Enter num1: " ))
b = int(input("Enter num2: " ))
c = input("Enter operater: ")
if(c=='+'):
    print("Addition: ",a+b)
elif(c=='-'):
    print("Subtraction: ",a-b)
elif(c=='*'):
    print("Subtraction: ",a*b)
elif(c=='/'):
    print("Subtraction: ",a/b)
else:
    print(" Invalid Input! ")
